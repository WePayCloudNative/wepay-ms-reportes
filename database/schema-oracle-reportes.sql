-- WePay - esquema inicial para wepay-ms-reportes
-- Ejecutar con el usuario/esquema Oracle de reportería.
-- Requiere Oracle 12c o superior para columnas IDENTITY.
-- Para un esquema nuevo y vacío. No ejecutar de nuevo sobre tablas existentes.

CREATE TABLE pedidos_reporte (
    pedido_id            NUMBER(19, 0) NOT NULL,
    usuario_oid          VARCHAR2(255 CHAR),
    total                FLOAT(53),
    estado               VARCHAR2(255 CHAR),
    fecha_creacion       TIMESTAMP(6),
    fecha_entrega        TIMESTAMP(6),
    fecha_ultimo_evento  TIMESTAMP(6),
    CONSTRAINT pk_pedidos_reporte PRIMARY KEY (pedido_id)
);

CREATE TABLE detalle_pedido_reporte (
    id               NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    pedido_id        NUMBER(19, 0) NOT NULL,
    producto_id      NUMBER(19, 0) NOT NULL,
    nombre_producto  VARCHAR2(255 CHAR) NOT NULL,
    precio_unitario  FLOAT(53) NOT NULL,
    cantidad         NUMBER(10, 0) NOT NULL,
    CONSTRAINT pk_detalle_pedido_reporte PRIMARY KEY (id),
    CONSTRAINT fk_detalle_pedido_reporte_pedido
      FOREIGN KEY (pedido_id) REFERENCES pedidos_reporte (pedido_id)
);

CREATE INDEX idx_detalle_reporte_pedido ON detalle_pedido_reporte (pedido_id);

CREATE TABLE eventos_procesados_reporte (
    event_id             VARCHAR2(255 CHAR) NOT NULL,
    pedido_id            NUMBER(19, 0),
    tipo_evento          VARCHAR2(255 CHAR),
    fecha_procesamiento  TIMESTAMP(6),
    CONSTRAINT pk_eventos_procesados_reporte PRIMARY KEY (event_id)
);

